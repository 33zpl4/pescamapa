// Builds the theme stylesheet from the Astro components' styles, so the
// WordPress site looks exactly like the current one:
//   node wordpress/build/generar-css.mjs
// Each component's scoped <style> is wrapped in its root selector with native
// CSS nesting; ":global(x)" becomes "x". Output: themes/pescamapa/assets/pescamapa.css
import { readFileSync, writeFileSync } from 'node:fs';

const raiz = new URL('../../', import.meta.url);
const leer = (p) => readFileSync(new URL(p, raiz), 'utf8');
const estilo = (p) => {
	const s = leer(p);
	const m = s.match(/<style>([\s\S]*?)<\/style>/);
	return m ? m[1].replace(/:global\(([^)]+)\)/g, '$1') : '';
};
// Wrap in a scope; the scope's own selector inside becomes "&".
const envolver = (scope, css, propio = scope) => {
	const esc = propio.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
	const cuerpo = css.replace(new RegExp(`(^|[\\s,}])${esc}(?=[\\s.:{,\\[])`, 'g'), '$1&');
	return `\n/* ${scope} */\n${scope} {${cuerpo}}\n`;
};

let css = leer('src/styles/global.css').replace(/@import[^;]+;\n/g, '');
css = `/* Pescamapa theme — generated by wordpress/build/generar-css.mjs from the
   Astro components. Edit the components or this file's generator, not here. */
@import url('fuentes.css');
${css}`;
css += envolver('.nav', estilo('src/components/Header.astro'));
css += envolver('footer', estilo('src/components/Footer.astro'));
css += envolver('.foto', estilo('src/components/Foto.astro'));
css += envolver('.mapa-hero', estilo('src/components/MapaHero.astro'));
css += envolver('.curvas', estilo('src/components/Curvas.astro'));
css += envolver('.mapa', estilo('src/components/Mapa.astro'));
css += envolver('.v-inicio', estilo('src/vistas/Inicio.astro'));
css += envolver('.v-destino', estilo('src/vistas/Destino.astro'));
css += envolver('.v-especie', estilo('src/vistas/Especie.astro'));
css += envolver('.v-mapa', estilo('src/vistas/MapaPagina.astro'));
css += envolver('.v-creditos', estilo('src/vistas/Creditos.astro'));
css += envolver('.v-404', '');
css += `
/* Base layout: draft banner, post content blocks */
.borrador { background: var(--warn-bg); border-bottom: 1px solid var(--warn-line); font-size: 14px; padding: 10px 0; position: relative; z-index: 10; }
.prose .wp-block-quote, .prose blockquote { margin: 1em 0; padding: 12px 16px; background: var(--warn-bg); border-left: 3px solid var(--warn-line); border-radius: 6px; font-size: 14px; }
.prose .wp-block-quote p, .prose blockquote p { margin: 0; }
`;
writeFileSync(new URL('wordpress/themes/pescamapa/assets/pescamapa.css', raiz), css);
console.log(`pescamapa.css: ${(css.length / 1024).toFixed(1)} KB`);
